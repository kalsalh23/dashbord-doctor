-- كتالوج الأدوية المشترك (يستخدمه البحث الفوري في الكشف الحي وصفحة الوصفة)
create table if not exists public.medication_catalog (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  dosage text,
  duration text,
  instructions text,
  created_at timestamptz not null default now()
);
create index if not exists medication_catalog_name_idx on public.medication_catalog (name);

alter table public.medication_catalog enable row level security;

drop policy if exists medcat_select on public.medication_catalog;
create policy medcat_select on public.medication_catalog for select to authenticated
  using (true);
drop policy if exists medcat_insert on public.medication_catalog;
create policy medcat_insert on public.medication_catalog for insert to authenticated
  with check (true);

